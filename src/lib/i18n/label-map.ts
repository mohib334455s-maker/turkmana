export function pickLocaleLabel(label: string, locale: 'fa' | 'en') {
  const raw = String(label ?? '').trim();
  if (!raw) return '';
  if (raw.includes('|')) {
    const [fa, en] = raw.split('|');
    return locale === 'en' ? (en || fa).trim() : fa.trim();
  }
  if (locale === 'en') return FA_EN_LABELS[raw] ?? raw;
  return raw;
}
